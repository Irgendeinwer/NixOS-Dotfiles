#!/usr/bin/env python3
"""Reconcile selected Zen Mods without taking ownership of the whole profile.

Run `check` before Home Manager's write boundary and `apply` after it. Mod
assets are fixed-output Nix store files; no network access is performed here.
Only regular files with recognized hashes are replaced. Browser-owned registry
entries and unlisted files are retained, and replaced files get unique backups.
"""

import argparse
import fcntl
import hashlib
import json
import os
import re
import stat
import sys
import tempfile
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path

UUID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\Z")
SHA256 = re.compile(r"[0-9a-f]{64}\Z")
STATE = "nixos-dotfiles-zen-mods.json"
UPSTREAM_MARKERS = (
    "zen-prefs-nix-managed.json",
    "zen-extension-buttons-nix-managed.json",
)
CSS_PREFIX = b"/* Zen Mods - Generated by ZenMods.\n* FILE GENERATED AT: "
CSS_HEADER = (
    CSS_PREFIX
    + b"NixOS-Dotfiles reconciliation\n"
    + b"* DO NOT EDIT THIS FILE DIRECTLY!\n"
    + b"* Your changes will be overwritten.\n"
    + b"* Instead, go to the preferences and edit the mods there.\n"
    + b"*/\n"
)


class AdoptionError(Exception):
    pass


@dataclass(frozen=True)
class Snapshot:
    path: Path
    data: bytes | None
    mode: int = 0o600


@dataclass(frozen=True)
class Update:
    old: Snapshot
    data: bytes


def exists(path):
    return os.path.lexists(path)


def require_dir(path, *, missing_ok=False):
    try:
        info = path.lstat()
    except FileNotFoundError:
        if missing_ok:
            return
        raise AdoptionError(f"directory is missing: {path}") from None
    if not stat.S_ISDIR(info.st_mode):
        raise AdoptionError(f"expected a real directory, not a file or symlink: {path}")


def snapshot(path):
    """Read one regular file, refusing even dangling or Nix-store symlinks."""
    try:
        before = path.lstat()
    except FileNotFoundError:
        return Snapshot(path, None)
    if not stat.S_ISREG(before.st_mode):
        raise AdoptionError(
            f"expected a regular file, not a symlink or special file: {path}"
        )
    flags = os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK
    try:
        fd = os.open(path, flags)
        with os.fdopen(fd, "rb") as stream:
            current = os.fstat(stream.fileno())
            if not stat.S_ISREG(current.st_mode) or (
                current.st_dev,
                current.st_ino,
            ) != (
                before.st_dev,
                before.st_ino,
            ):
                raise AdoptionError(f"file changed while being inspected: {path}")
            return Snapshot(path, stream.read(), stat.S_IMODE(current.st_mode) & 0o777)
    except OSError as exc:
        raise AdoptionError(f"cannot safely read {path}: {exc}") from exc


def parse_json(data, path):
    def unique_object(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise AdoptionError(f"duplicate JSON key {key!r} in {path}")
            result[key] = value
        return result

    def bad_constant(value):
        raise AdoptionError(f"invalid JSON value {value} in {path}")

    try:
        return json.loads(
            data, object_pairs_hook=unique_object, parse_constant=bad_constant
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise AdoptionError(f"invalid JSON in {path}: {exc}") from exc


def encoded_json(value):
    return (json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def check_sha(value, subject):
    if not isinstance(value, str) or not SHA256.fullmatch(value):
        raise AdoptionError(f"invalid SHA-256 for {subject}")


def load_mods(path):
    raw = Path(path).read_bytes()
    manifest = parse_json(raw, path)
    if not isinstance(manifest, list):
        raise AdoptionError("mod manifest must be a list")
    seen = set()
    result = []
    for mod in manifest:
        if not isinstance(mod, dict) or not isinstance(mod.get("entry"), dict):
            raise AdoptionError("invalid mod entry in manifest")
        entry = mod["entry"]
        mod_id = entry.get("id")
        if not isinstance(mod_id, str) or not UUID.fullmatch(mod_id) or mod_id in seen:
            raise AdoptionError(f"invalid or duplicate mod ID: {mod_id!r}")
        seen.add(mod_id)
        if entry.get("enabled") is not True:
            raise AdoptionError(f"manifest must enable mod {mod_id}")
        files = mod.get("files")
        if not isinstance(files, dict) or "chrome.css" not in files:
            raise AdoptionError(f"mod {mod_id} has no chrome.css")
        if set(files) - {"chrome.css", "preferences.json"}:
            raise AdoptionError(f"unexpected managed asset for mod {mod_id}")
        if bool(entry.get("preferences")) != ("preferences.json" in files):
            raise AdoptionError(
                f"preferences metadata and assets disagree for mod {mod_id}"
            )
        contents = {}
        for name, spec in files.items():
            if not isinstance(spec, dict):
                raise AdoptionError(f"invalid asset declaration for {mod_id}/{name}")
            expected = spec.get("sha256")
            check_sha(expected, f"{mod_id}/{name}")
            previous = spec.get("acceptedPreviousSha256", [])
            if not isinstance(previous, list):
                raise AdoptionError(f"invalid previous hashes for {mod_id}/{name}")
            for value in previous:
                check_sha(value, f"{mod_id}/{name}")
            source = spec.get("source")
            if not isinstance(source, str) or not os.path.isabs(source):
                raise AdoptionError(f"invalid source for {mod_id}/{name}")
            try:
                data = Path(source).read_bytes()
            except OSError as exc:
                raise AdoptionError(
                    f"cannot read pinned source {source}: {exc}"
                ) from exc
            if digest(data) != expected:
                raise AdoptionError(f"pinned source hash mismatch: {mod_id}/{name}")
            try:
                data.decode("utf-8")
            except UnicodeDecodeError as exc:
                raise AdoptionError(
                    f"invalid UTF-8 in pinned source {mod_id}/{name}"
                ) from exc
            if name == "preferences.json" and not isinstance(
                parse_json(data, source), list
            ):
                raise AdoptionError(f"mod preferences must be a JSON list: {mod_id}")
            contents[name] = data
        result.append((entry, files, contents))
    return result


def load_state(snap):
    if snap.data is None:
        return {"schema": 1, "managed": {}}
    state = parse_json(snap.data, snap.path)
    if (
        not isinstance(state, dict)
        or set(state) != {"schema", "managed"}
        or state["schema"] != 1
        or not isinstance(state["managed"], dict)
    ):
        raise AdoptionError(f"unknown or invalid mod state in {snap.path}")
    for mod_id, files in state["managed"].items():
        if not UUID.fullmatch(mod_id) or not isinstance(files, dict):
            raise AdoptionError(f"invalid recorded mod state in {snap.path}")
        if set(files) - {"chrome.css", "preferences.json"}:
            raise AdoptionError(f"invalid recorded asset in {snap.path}")
        for name, value in files.items():
            check_sha(value, f"recorded {mod_id}/{name}")
    return state


def same_stylesheet(left, right):
    # Zen changes this timestamp whenever it regenerates an otherwise identical
    # stylesheet. Avoid replacing/backing it up just for that timestamp.
    def without_timestamp(data):
        if not data.startswith(CSS_PREFIX):
            return data
        _, sep, rest = data[len(CSS_PREFIX) :].partition(b"\n")
        return CSS_PREFIX + b"<timestamp>\n" + rest if sep else data

    return left is not None and without_timestamp(left) == without_timestamp(right)


def comment(value):
    # Metadata belongs in a CSS comment, never in executable CSS.
    if value is None:
        value = "undefined"
    return str(value).replace("*/", "* /").replace("\r", " ").replace("\n", " ")


def stylesheet(registry, css_by_id):
    output = bytearray(CSS_HEADER)
    for mod_id, entry in registry.items():
        if not entry.get("enabled", True):
            continue
        output.extend(f"\n/* Name: {comment(entry.get('name'))} */\n".encode())
        output.extend(
            f"/* Description: {comment(entry.get('description'))} */\n".encode()
        )
        output.extend(f"/* Author: @{comment(entry.get('author'))} */\n".encode())
        if entry.get("_readmeURL"):
            output.extend(f"/* Readme: {comment(entry.get('readme'))} */\n".encode())
        output.extend(css_by_id[mod_id])
    output.extend(b"\n/* End of Zen Mods */\n")
    return bytes(output)


def plan(profile, mods):
    """Read and validate every input before returning any planned writes."""
    if not profile.is_dir():
        raise AdoptionError(f"existing profile directory is missing: {profile}")
    for marker in UPSTREAM_MARKERS:
        path = profile / marker
        if exists(path):
            raise AdoptionError(
                f"{path} can trigger upstream prefs.js cleanup; inspect and move it "
                "safely aside before switching (see docs/zen-browser.md)"
            )
    chrome = profile / "chrome"
    root = chrome / "zen-themes"
    require_dir(chrome, missing_ok=True)
    require_dir(root, missing_ok=True)

    watches = []
    writes = []

    def watch(path):
        item = snapshot(path)
        watches.append(item)
        return item

    def change(old, data):
        if old.data != data:
            writes.append(Update(old, data))

    registry_snap = watch(profile / "zen-themes.json")
    registry = (
        {}
        if registry_snap.data is None
        else parse_json(registry_snap.data, registry_snap.path)
    )
    if not isinstance(registry, dict):
        raise AdoptionError(f"mod registry must be a JSON object: {registry_snap.path}")
    for key, entry in registry.items():
        if not isinstance(entry, dict):
            raise AdoptionError(f"invalid mod registry entry: {key!r}")
        if "enabled" in entry and not isinstance(entry["enabled"], bool):
            raise AdoptionError(f"invalid enabled state in mod registry: {key!r}")

    state_snap = watch(profile / STATE)
    state = load_state(state_snap)
    new_state = {"schema": 1, "managed": dict(state["managed"])}
    merged = {}
    css_by_id = {}
    declared = set()

    for entry, files, contents in mods:
        mod_id = entry["id"]
        declared.add(mod_id)
        existing = registry.get(mod_id, {})
        if existing and existing.get("id") != mod_id:
            raise AdoptionError(f"mod registry ID does not match its key: {mod_id}")
        # Keep unrecognized metadata, while making the declared mod active and
        # pointing its known metadata at the pinned source/version.
        merged[mod_id] = {**existing, **entry}
        mod_dir = root / mod_id
        require_dir(mod_dir, missing_ok=True)
        recorded = state["managed"].get(mod_id, {})
        new_state["managed"][mod_id] = {
            name: spec["sha256"] for name, spec in files.items()
        }
        for name, spec in files.items():
            old = watch(mod_dir / name)
            if old.data is not None:
                accepted = {spec["sha256"], *spec.get("acceptedPreviousSha256", [])}
                if name in recorded:
                    accepted.add(recorded[name])
                actual = digest(old.data)
                if actual not in accepted:
                    raise AdoptionError(
                        f"unexpected SHA-256 for {old.path}: {actual}. "
                        "It was not changed; back up and inspect this file before "
                        "explicitly migrating it (see docs/zen-browser.md)."
                    )
            change(old, contents[name])
        css_by_id[mod_id] = contents["chrome.css"]

    # Unlisted mods, including their enabled state and other files, are not
    # managed. Their CSS is included just as Zen includes enabled registry mods.
    for mod_id, entry in registry.items():
        if mod_id in declared:
            continue
        merged[mod_id] = entry
        if not entry.get("enabled", True):
            continue
        if not UUID.fullmatch(mod_id) or entry.get("id") != mod_id:
            raise AdoptionError(
                f"unsafe or inconsistent enabled extra mod ID: {mod_id!r}"
            )
        mod_dir = root / mod_id
        require_dir(mod_dir)
        old = watch(mod_dir / "chrome.css")
        if old.data is None:
            raise AdoptionError(f"enabled extra mod has no stylesheet: {old.path}")
        try:
            old.data.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise AdoptionError(
                f"invalid UTF-8 in extra mod stylesheet: {old.path}"
            ) from exc
        css_by_id[mod_id] = old.data

    # Semantic comparison avoids rewriting browser-formatted JSON on every
    # activation, but order matters for CSS cascade and is made deterministic.
    if (
        registry != merged
        or list(registry) != list(merged)
        or registry_snap.data is None
    ):
        change(registry_snap, encoded_json(merged))
    css_snap = watch(chrome / "zen-themes.css")
    css = stylesheet(merged, css_by_id)
    if not same_stylesheet(css_snap.data, css):
        change(css_snap, css)
    if state != new_state or state_snap.data is None:
        change(state_snap, encoded_json(new_state))
    return writes, watches


@contextmanager
def profile_lock(profile, *, create):
    """Hold Gecko's POSIX record lock, not flock's incompatible lock type."""
    legacy = profile / "lock"
    if exists(legacy):
        raise AdoptionError(
            f"legacy Zen lock exists: {legacy}; close Zen and inspect it"
        )
    lock = profile / ".parentlock"
    flags = os.O_WRONLY | os.O_NOFOLLOW | os.O_NONBLOCK | (os.O_CREAT if create else 0)
    try:
        fd = os.open(lock, flags, 0o600)
    except FileNotFoundError:
        if create:
            raise
        # A check must not create the lock before Home Manager's write boundary.
        yield
        return
    except OSError as exc:
        raise AdoptionError(f"cannot open Zen profile lock {lock}: {exc}") from exc
    try:
        info = os.fstat(fd)
        if not stat.S_ISREG(info.st_mode):
            raise AdoptionError(f"Zen profile lock is not a regular file: {lock}")
        try:
            fcntl.lockf(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as exc:
            raise AdoptionError(
                f"cannot lock {lock}; close all Zen processes: {exc}"
            ) from exc
        on_disk = lock.lstat()
        if (info.st_dev, info.st_ino) != (on_disk.st_dev, on_disk.st_ino):
            raise AdoptionError(f"Zen profile lock changed while locking: {lock}")
        if exists(legacy):
            raise AdoptionError(
                f"legacy Zen lock exists: {legacy}; close Zen and inspect it"
            )
        yield
    finally:
        os.close(fd)


def ensure_parent(profile, parent):
    """Create missing profile subdirectories, never traversing symlink children."""
    current = profile
    for part in parent.relative_to(profile).parts:
        current = current / part
        try:
            current.mkdir(mode=0o700)
        except FileExistsError:
            pass
        require_dir(current)


def make_temp(parent, data, mode):
    fd, name = tempfile.mkstemp(prefix=".nixos-dotfiles-zen-", dir=parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            os.fchmod(stream.fileno(), mode)
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
    except BaseException:
        os.unlink(name)
        raise
    return Path(name)


def create_backup(profile, backup_root, writes):
    existing = [item for item in writes if item.old.data is not None]
    if not existing:
        return None
    backup_root.mkdir(mode=0o700, parents=True, exist_ok=True)
    require_dir(backup_root)
    backup = Path(tempfile.mkdtemp(prefix=f"{profile.name}-", dir=backup_root))
    for item in existing:
        relative = item.old.path.relative_to(profile)
        dest = backup / relative
        dest.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        with dest.open("xb") as stream:
            os.fchmod(stream.fileno(), 0o600)
            stream.write(item.old.data)
    report = {
        "profile": str(profile),
        "saved": [str(item.old.path.relative_to(profile)) for item in existing],
        "originalModes": {
            str(item.old.path.relative_to(profile)): f"{item.old.mode:04o}"
            for item in existing
        },
        "created": [
            str(item.old.path.relative_to(profile))
            for item in writes
            if item.old.data is None
        ],
    }
    with (backup / "backup-manifest.json").open("xb") as stream:
        os.fchmod(stream.fileno(), 0o600)
        stream.write(encoded_json(report))
    return backup


def apply(profile, backup_root, writes, watches):
    if not writes:
        print("zen-mods: already reconciled")
        return
    backup = create_backup(profile, backup_root, writes)
    if backup:
        print(f"zen-mods: saved replaced files in {backup}", flush=True)
    staged = []
    committed = []
    try:
        for item in writes:
            ensure_parent(profile, item.old.path.parent)
            staged.append(
                (item, make_temp(item.old.path.parent, item.data, item.old.mode))
            )
        # Check all inputs again before the first replacement. A running Zen is
        # excluded by the lock; this also catches another editor changing files.
        for old in watches:
            if snapshot(old.path) != old:
                raise AdoptionError(f"file changed during reconciliation: {old.path}")
        for item, temporary in staged:
            if snapshot(item.old.path) != item.old:
                raise AdoptionError(
                    f"file changed during reconciliation: {item.old.path}"
                )
            os.replace(temporary, item.old.path)
            committed.append(item)
    except (OSError, AdoptionError) as exc:
        failures = []
        for item in reversed(committed):
            try:
                current = snapshot(item.old.path)
                if current.data != item.data:
                    failures.append(str(item.old.path))
                    continue  # Never overwrite another writer's changes.
                if item.old.data is None:
                    item.old.path.unlink()
                else:
                    original = make_temp(
                        item.old.path.parent, item.old.data, item.old.mode
                    )
                    try:
                        os.replace(original, item.old.path)
                    finally:
                        if exists(original):
                            original.unlink()
            except (OSError, AdoptionError):
                failures.append(str(item.old.path))
        detail = (
            f"; automatic rollback failed or was unsafe for: {', '.join(failures)}"
            if failures
            else "; completed writes were rolled back"
        )
        where = f"; backups: {backup}" if backup else ""
        raise AdoptionError(f"reconciliation failed: {exc}{detail}{where}") from exc
    finally:
        for _, temporary in staged:
            if exists(temporary):
                temporary.unlink()
    print(f"zen-mods: reconciled {len(writes)} files")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["check", "apply"])
    parser.add_argument("--profile", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--backup-root", type=Path, required=True)
    args = parser.parse_args()
    try:
        if not args.profile.is_dir():
            raise AdoptionError(
                f"existing profile directory is missing: {args.profile}"
            )
        require_dir(args.backup_root, missing_ok=True)
        mods = load_mods(args.manifest)
        with profile_lock(args.profile, create=args.mode == "apply"):
            writes, watches = plan(args.profile, mods)
            if args.mode == "apply":
                apply(args.profile, args.backup_root, writes, watches)
            else:
                print(f"zen-mods: preflight passed ({len(writes)} files would change)")
    except (AdoptionError, OSError, ValueError) as exc:
        print(f"zen-mods: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
